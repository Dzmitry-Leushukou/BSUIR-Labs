#!/bin/bash


[ $# -eq 0 ] && { echo "Использование: $0 файл"; exit 1; }
[ ! -f "$1" ] && { echo "Ошибка: файл $1 не найден"; exit 1; }

sed -E '
    # Защита десятичных точек
    s/([0-9])\.([0-9])/\1@DOT@\2/g
    s/(^|[[:space:]])\.([0-9])/\1@DOT@\2/g
    
    # Заглавная в начале документа (латиница + кириллица)
    s/^([[:space:]]*)([a-z])/\1\U\2/
    s/^([[:space:]]*)([а-яё])/\1\U\2/
    
    # Заглавные после . ! ? с пробелами
    s/([.!?][[:space:]]+)([a-z])/\1\U\2/g
    s/([.!?][[:space:]]+)([а-яё])/\1\U\2/g
    
    # Заглавные после . ! ? без пробелов (вставляем пробел)
    s/([.!?])([a-z])/\1 \U\2/g
    s/([.!?])([а-яё])/\1 \U\2/g
    
    # Восстановление точек
    s/@DOT@/./g
' "$1"

exit 0
