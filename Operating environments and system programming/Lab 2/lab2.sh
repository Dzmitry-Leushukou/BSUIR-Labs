#!/bin/bash

# Проверка аргументов
[ $# -eq 0 ] && { echo "Использование: $0 файл"; exit 1; }
[ ! -f "$1" ] && { echo "Ошибка: файл $1 не найден"; exit 1; }

# Читаем весь файл в одну строку, обрабатываем переносы
sed -E ':a; $!{N; ba}; 
    # 1. Защищаем точки внутри чисел (цифра.цифра)
    s/([0-9])\.([0-9])/\1@DOT@\2/g
    
    # 2. Защищаем точки перед числами (пробел.цифра или начало.цифра)
    s/(^|[[:space:]])\.([0-9])/\1@DOT@\2/g
    
    # 3. ЗАГЛАВНАЯ В НАЧАЛЕ ДОКУМЕНТА
    s/^([[:space:]]*)([a-zа-яё])/\1\U\2/
    
    # 4. ЗАГЛАВНЫЕ ПОСЛЕ . ! ? (С ЛЮБЫМИ ПРОБЕЛАМИ И ПЕРЕНОСАМИ СТРОК)
    s/([.!?][[:space:]]+)([a-zа-яё])/\1\U\2/g
    
    # 5. ЗАГЛАВНЫЕ ПОСЛЕ . ! ? (БЕЗ ПРОБЕЛА - ВСТАВЛЯЕМ ПРОБЕЛ)
    s/([.!?])([a-zа-яё])/\1 \U\2/g
    
    # 6. Восстанавливаем точки в числах
    s/@DOT@/./g
' "$1"

exit 0
